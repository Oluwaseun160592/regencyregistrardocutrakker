-- 1. USERS & ROLES TABLE
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL DEFAULT 'Staff',
    active INT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. ACCOUNT OFFICERS / RELATIONSHIP MANAGERS TABLE
CREATE TABLE IF NOT EXISTS public.account_officers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    officer_code VARCHAR(50),
    email VARCHAR(255),
    phone VARCHAR(50),
    department VARCHAR(100),
    active INT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. DOCUMENTS TABLE
CREATE TABLE IF NOT EXISTS public.documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_no VARCHAR(100) UNIQUE NOT NULL,
    client_name VARCHAR(255) NOT NULL,
    client_account VARCHAR(100) NOT NULL,
    chn_number VARCHAR(100),
    account_officer VARCHAR(255) NOT NULL,
    document_type VARCHAR(100) NOT NULL,
    stock_symbol VARCHAR(50),
    units BIGINT DEFAULT 0,
    description TEXT,
    priority VARCHAR(50) NOT NULL DEFAULT 'Normal',
    submission_date DATE NOT NULL DEFAULT CURRENT_DATE,
    due_date DATE,
    status VARCHAR(50) NOT NULL DEFAULT 'Received',
    
    -- 3-Tier Approval Pipeline
    approval_status VARCHAR(50) NOT NULL DEFAULT 'Pending Level 1',
    level1_approved INT DEFAULT 0,
    level1_user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    level1_user_name VARCHAR(255),
    level1_date TIMESTAMPTZ,
    level1_notes TEXT,
    
    level2_approved INT DEFAULT 0,
    level2_user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    level2_user_name VARCHAR(255),
    level2_date TIMESTAMPTZ,
    level2_notes TEXT,
    
    level3_approved INT DEFAULT 0,
    level3_user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    level3_user_name VARCHAR(255),
    level3_date TIMESTAMPTZ,
    level3_notes TEXT,
    
    queried_at_level INT DEFAULT 0,
    query_reason TEXT,
    
    -- Registrar Collection & Dispatch Particulars
    registrar_name VARCHAR(255),
    collection_status VARCHAR(50) NOT NULL DEFAULT 'Pending Collection',
    collector_name VARCHAR(255),
    collector_phone VARCHAR(50),
    collected_date TIMESTAMPTZ,
    dispatch_waybill_no VARCHAR(100),
    collection_method VARCHAR(100),
    collection_proof_name VARCHAR(255),
    collection_proof_path TEXT,
    collection_notes TEXT,
    
    -- Attached Files & Metadata
    file_name VARCHAR(255),
    file_path TEXT,
    remarks TEXT,
    created_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. APPROVAL LOGS TABLE
CREATE TABLE IF NOT EXISTS public.approval_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES public.documents(id) ON DELETE CASCADE,
    level INT NOT NULL,
    level_name VARCHAR(100) NOT NULL,
    action VARCHAR(50) NOT NULL,
    user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    user_name VARCHAR(255),
    user_role VARCHAR(50),
    comments TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. STATUS & REASSIGNMENT HISTORY TABLE
CREATE TABLE IF NOT EXISTS public.status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES public.documents(id) ON DELETE CASCADE,
    old_status VARCHAR(50),
    new_status VARCHAR(50) NOT NULL,
    comment TEXT,
    changed_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    changed_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. SYSTEM AUDIT LOGS TABLE
CREATE TABLE IF NOT EXISTS public.audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
    document_id BIGINT REFERENCES public.documents(id) ON DELETE SET NULL,
    action VARCHAR(100) NOT NULL,
    details TEXT,
    ip_address VARCHAR(100),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

